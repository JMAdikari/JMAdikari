#!/usr/bin/env python3
"""Synchronize Featured and Starred repository blocks in README.md."""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from datetime import datetime
import urllib.parse
import urllib.request
from typing import Any

FEATURED_START = "FEATURED-REPOS:START"
FEATURED_END = "FEATURED-REPOS:END"
STARRED_START = "STARRED-REPOS:START"
STARRED_END = "STARRED-REPOS:END"


def escape_markdown(value: str | None) -> str:
    if not value:
        return "—"
    text = value.replace("\r\n", "\n").replace("\r", "\n")
    text = text.replace("|", r"\|")
    text = text.replace("\n", "<br/>")
    return text.strip() or "—"


def github_api_get_paginated(url: str, token: str | None = None) -> list[dict[str, Any]]:
    page = 1
    results: list[dict[str, Any]] = []
    while True:
        separator = "&" if "?" in url else "?"
        page_url = f"{url}{separator}per_page=100&page={page}"
        request = urllib.request.Request(page_url)
        request.add_header("Accept", "application/vnd.github+json")
        request.add_header("X-GitHub-Api-Version", "2022-11-28")
        if token:
            request.add_header("Authorization", "Bearer " + token)
        with urllib.request.urlopen(request) as response:
            payload = json.loads(response.read().decode("utf-8"))
        if not isinstance(payload, list):
            raise RuntimeError(f"Unexpected GitHub API response for {page_url}: {payload}")
        results.extend(payload)
        if len(payload) < 100:
            break
        page += 1
    return results


def pushed_at_sort_value(repo: dict[str, Any]) -> float:
    pushed_at = repo.get("pushed_at")
    if not pushed_at:
        return 0.0
    try:
        return datetime.fromisoformat(pushed_at.replace("Z", "+00:00")).timestamp()
    except ValueError:
        return 0.0


def rank_featured_repositories(repositories: list[dict[str, Any]], limit: int) -> list[dict[str, Any]]:
    candidates = [repo for repo in repositories if not repo.get("fork") and not repo.get("private")]
    candidates.sort(
        key=lambda repo: (
            -(repo.get("stargazers_count") or 0),
            -pushed_at_sort_value(repo),
            (repo.get("name") or "").lower(),
        ),
    )
    return candidates[:limit]


def rank_starred_repositories(starred: list[dict[str, Any]], limit: int) -> list[dict[str, Any]]:
    normalized: list[dict[str, Any]] = []
    for entry in starred:
        if "repo" in entry and isinstance(entry.get("repo"), dict):
            normalized.append(entry["repo"])
        else:
            normalized.append(entry)
    normalized.sort(
        key=lambda repo: (
            -(repo.get("stargazers_count") or 0),
            -pushed_at_sort_value(repo),
            (repo.get("full_name") or repo.get("name") or "").lower(),
        ),
    )
    return normalized[:limit]


def render_featured_block(owner: str, repositories: list[dict[str, Any]], limit: int) -> str:
    featured = rank_featured_repositories(repositories, limit)
    lines: list[str] = [
        "<!-- Generated by scripts/sync_readme_repositories.py -->",
        f"_Top {limit} non-fork public repositories by stars, then recent push date._",
        "",
    ]
    if not featured:
        lines.append("_No public repositories available._")
        return "\n".join(lines)

    lines.extend(["<p align=\"center\">"])
    for repo in featured:
        name = repo.get("name", "")
        html_url = repo.get("html_url", "")
        encoded_name = urllib.parse.quote(name, safe="")
        lines.append(
            f"  <a href=\"{html_url}\"><img width=\"48%\" "
            f"src=\"https://github-readme-stats.vercel.app/api/pin/?username={owner}&repo={encoded_name}"
            "&theme=tokyonight&hide_border=true&bg_color=0D1117&title_color=6C63FF&icon_color=F1A11E"
            f"&text_color=C9D1D9\" alt=\"{escape_markdown(name)}\"/></a>"
        )
    lines.extend(["</p>", "", "| Repository | Description | Language | Stars | Link |", "|---|---|---|---:|---|"])
    for repo in featured:
        name = escape_markdown(repo.get("name"))
        html_url = repo.get("html_url", "")
        description = escape_markdown(repo.get("description"))
        language = escape_markdown(repo.get("language"))
        stars = repo.get("stargazers_count") or 0
        lines.append(
            f"| [{name}]({html_url}) | {description} | {language} | {stars} | [Open ↗]({html_url}) |"
        )
    return "\n".join(lines)


def render_starred_block(starred: list[dict[str, Any]], limit: int) -> str:
    selected = rank_starred_repositories(starred, limit)
    lines: list[str] = [
        "<!-- Generated by scripts/sync_readme_repositories.py -->",
        f"_Current starred repositories (up to {limit})._",
        "",
    ]
    if not selected:
        lines.append("_No starred repositories found._")
        return "\n".join(lines)

    lines.extend(["| Repository | Description | Language | Stars | Link |", "|---|---|---|---:|---|"])
    for repo in selected:
        full_name = escape_markdown(repo.get("full_name") or repo.get("name"))
        html_url = repo.get("html_url", "")
        description = escape_markdown(repo.get("description"))
        language = escape_markdown(repo.get("language"))
        stars = repo.get("stargazers_count") or 0
        lines.append(
            f"| [{full_name}]({html_url}) | {description} | {language} | {stars} | [Open ↗]({html_url}) |"
        )
    return "\n".join(lines)


def replace_marked_block(content: str, start_marker: str, end_marker: str, new_body: str) -> str:
    pattern = re.compile(
        rf"(?P<start><!-- {re.escape(start_marker)} -->)\n.*?\n(?P<end><!-- {re.escape(end_marker)} -->)",
        flags=re.DOTALL,
    )
    replacement = rf"\g<start>\n{new_body}\n\g<end>"
    updated, count = pattern.subn(replacement, content, count=1)
    if count != 1:
        raise ValueError(f"Could not find block markers: {start_marker} / {end_marker}")
    return updated


def synchronize_readme(readme_path: str, owner: str, featured_limit: int, starred_limit: int, token: str | None) -> bool:
    with open(readme_path, "r", encoding="utf-8") as handle:
        original = handle.read()

    repositories = github_api_get_paginated(f"https://api.github.com/users/{owner}/repos?type=owner", token)
    starred = github_api_get_paginated(f"https://api.github.com/users/{owner}/starred", token)

    featured_block = render_featured_block(owner, repositories, featured_limit)
    starred_block = render_starred_block(starred, starred_limit)

    updated = replace_marked_block(original, FEATURED_START, FEATURED_END, featured_block)
    updated = replace_marked_block(updated, STARRED_START, STARRED_END, starred_block)

    if updated == original:
        return False
    with open(readme_path, "w", encoding="utf-8") as handle:
        handle.write(updated)
    return True


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Sync featured/starred repositories in README markers.")
    parser.add_argument("--readme", default="README.md", help="Path to README file.")
    parser.add_argument("--owner", default=os.getenv("GITHUB_REPOSITORY_OWNER"), help="GitHub owner/user.")
    parser.add_argument(
        "--featured-limit",
        type=int,
        default=int(os.getenv("FEATURED_REPOS_LIMIT", "6")),
        help="Max featured repositories to render.",
    )
    parser.add_argument(
        "--starred-limit",
        type=int,
        default=int(os.getenv("STARRED_REPOS_LIMIT", "15")),
        help="Max starred repositories to render.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Run sync and report whether README would change; do not persist changes.",
    )
    return parser.parse_args(argv)


def main(argv: list[str]) -> int:
    args = parse_args(argv)
    owner = args.owner
    if not owner:
        print("Missing GitHub owner. Set --owner or GITHUB_REPOSITORY_OWNER.", file=sys.stderr)
        return 2

    token = os.getenv("GITHUB_TOKEN")
    readme_path = args.readme
    with open(readme_path, "r", encoding="utf-8") as handle:
        before = handle.read()

    changed = synchronize_readme(
        readme_path=readme_path,
        owner=owner,
        featured_limit=args.featured_limit,
        starred_limit=args.starred_limit,
        token=token,
    )
    if args.dry_run:
        if changed:
            with open(readme_path, "w", encoding="utf-8") as handle:
                handle.write(before)
        print("README would be updated." if changed else "README is already up to date.")
        return 1 if changed else 0

    print("README updated." if changed else "No README changes needed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
